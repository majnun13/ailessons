-- TASK 1
SELECT FIRST_NAME, SALARY, 
    CASE 
        WHEN SALARY < 3000 THEN 'COX ASAGI'
        WHEN SALARY <= 6999 THEN 'ASAGI'
        WHEN SALARY <= 11999 THEN 'ORTA'
        ELSE 'YUKSEK'
    END AS KATEQORIYA
FROM HR.EMPLOYEES;

-- TASK 2
SELECT FIRST_NAME, DEPARTMENT_ID,
    CASE DEPARTMENT_ID
        WHEN 10 THEN 'ADMIN'
        WHEN 20 THEN 'MARKETING'
        WHEN 60 THEN 'IT'
        WHEN 90 THEN 'REHBERLIK'
        ELSE 'DIGER'
    END AS SOBE_ADI
FROM HR.EMPLOYEES;

-- TASK 3
SELECT FIRST_NAME, NVL(MANAGER_ID, 0), NVL(COMMISSION_PCT, 0) AS KOMISSIYA
FROM HR.EMPLOYEES;

-- TASK 4
SELECT JOB_TITLE, MIN_SALARY, MAX_SALARY,
    CASE 
        WHEN (MAX_SALARY - MIN_SALARY) < 5000 THEN 'DAR'
        WHEN (MAX_SALARY - MIN_SALARY) <= 10000 THEN 'ORTA'
        ELSE 'GENIS'
    END AS ARALIQ
FROM HR.JOBS;

-- TASK 5
SELECT FIRST_NAME, SALARY, SALARY * (1 + NVL(COMMISSION_PCT, 0)) AS AYLIQ_GELIR,
    CASE 
        WHEN NVL(COMMISSION_PCT, 0) > 0 THEN 'SATICI'
        ELSE 'DIGER'
    END AS NOV
FROM HR.EMPLOYEES
ORDER BY AYLIQ_GELIR DESC;

-- TASK 6
SELECT FIRST_NAME, SALARY,
       CASE 
           WHEN COMMISSION_PCT IS NULL THEN 'Komissiyasiz'
           ELSE 'KOMISSIYALI'
       END AS Komissiya
FROM HR.EMPLOYEES;

-- 1. SEHV END AS'DAN SONRA YENİ ALIAS'DAN SONRA YA 2 DIRNAQ YA DA DIRNAQSIZ YAZILMALIDI 1 DIRNAQ STRING OLARAK QEBUL OLUNUR.
-- 2. SEHV SIMPLE CASE İLE NULL YOXLANILMASI ISTIFADE EDİLMESİ YANLIŞDIR, NORMAL CASE İSTİFADE OLUNMALIDIR.
-- 3. SEHV ELSE'DE COMMISSION_PCT'Yİ GERİ DÖNDÜRMEK TAMAMİLE YANLIŞDIR YAZILMASI GEREKEN "KOMMISSIYALIDIR".

-- TASK 7
SELECT FIRST_NAME, JOB_ID, SALARY,
    CASE 
        WHEN JOB_ID LIKE 'AD%' THEN 'REHBERLIK'
        WHEN (JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR') AND SALARY > 12000 THEN 'BOYUK MENECER'
        WHEN JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR' THEN 'MENECER'
        ELSE 'ISCI'
    END AS ROL
FROM HR.EMPLOYEES;

-- TASK 8
SELECT FIRST_NAME, SALARY, NVL(COMMISSION_PCT, 0), 
    CASE 
        WHEN NVL(COMMISSION_PCT, 0) >= 0.3 THEN 'YUKSEK'
        WHEN NVL(COMMISSION_PCT, 0) >= 0.2 THEN 'ORTA'
        ELSE 'ASAGI'
    END AS KOMMISSIYA_SEVIYYESI
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80
ORDER BY KOMMISSIYA_SEVIYYESI DESC, SALARY DESC;


-- TASK 9
SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
    CASE 
        WHEN DEPARTMENT_ID = 80 THEN SALARY * (1 + NVL(COMMISSION_PCT, 0))
        WHEN DEPARTMENT_ID = 50 AND SALARY < 3000 THEN SALARY * 1.15
        WHEN DEPARTMENT_ID = 50 AND SALARY >= 3000 THEN SALARY * 1.05
        WHEN DEPARTMENT_ID IS NULL THEN SALARY
        ELSE SALARY * 1.03
    END AS YENI_MAAS
FROM HR.EMPLOYEES
ORDER BY YENI_MAAS DESC;

-- TASK 10
SELECT FIRST_NAME, SALARY, NVL(COMMISSION_PCT, 0), (SALARY * 12 + SALARY * 12 * NVL(COMMISSION_PCT, 0)) AS ILLIK_GELIR,
    CASE 
        WHEN  SALARY * 12 + SALARY * 12 * NVL(COMMISSION_PCT, 0)< 50000 THEN 'ASAGI'
        WHEN SALARY * 12 + SALARY * 12 * NVL(COMMISSION_PCT, 0) <= 149999 THEN 'ORTA'
        ELSE 'YUKSEK'
    END AS GELIR_SEVIYYESI
FROM HR.EMPLOYEES
ORDER BY ILLIK_GELIR DESC;