-- TASK 1
SELECT JOB_ID, COUNT(EMPLOYEE_ID) AS ISCI_SAYI, FLOOR(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY JOB_ID
ORDER BY ISCI_SAYI DESC;

-- TASK 2
SELECT DEPARTMENT_ID, MIN(SALARY) AS MIN_MAAS, MAX(SALARY) AS MAX_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID ASC;

-- TASK 3
SELECT D.DEPARTMENT_NAME, L.CITY 
FROM HR.DEPARTMENTS D
LEFT JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID;

-- TASK 4
SELECT JOB_ID, SUM(SALARY) AS MAAS_CEMI
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING MAAS_CEMI > 50000
ORDER BY MAAS_CEMI DESC;

-- TASK 5
SELECT MANAGER_ID, COUNT(EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL
GROUP BY MANAGER_ID
HAVING ISCI_SAYI > 5;

-- TASK 6
SELECT L.CITY, COUNT(D.DEPARTMENT_ID) AS SOBE_SAYI
FROM HR.DEPARTMENTS D
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY L.CITY
ORDER BY SOBE_SAYI DESC;

-- TASK 7
SELECT E.FIRST_NAME, E.LAST_NAME, D.DEPARTMENT_NAME 
FROM HR.EMPLOYEES E
FULL JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE E.DEPARTMENT_ID IS NULL OR D.DEPARTMENT_ID IS NULL;

-- TASK 8 
SELECT D.DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING ISCI_SAYI > 3;

-- 1. sehv ON'da E.DEPARTMENT_ID = ....  olmalı idi lakin DEPARTMENT_ID = ... yazılmışdı.
-- 2. sehv WHERE ile count(*) kimi funksiyalar işledilmez onun yerine HAVING olmalıdır çünkü bu bir aggregate function'dır.
-- 3. sehv E.FIRST_NAME çıxarılmalı idi çünki biz department_name'e göre group edirik ve bu sebebden eger select'de first_name de olsa xeta verecek idi.
-- elave qeyd: having ile count(*) yerine ıscı_sayı yazıldı çünki kodun readability'si daha yaxşı olsun arzuolunan bir şeydir.

-- TASK 9
SELECT D.DEPARTMENT_NAME, J.JOB_TITLE, COUNT(E.EMPLOYEE_ID) ISCI_SAYI, CEIL(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.JOBS J 
ON E.JOB_ID = J.JOB_ID
GROUP BY D.DEPARTMENT_NAME, J.JOB_TITLE
HAVING ISCI_SAYI >= 3
ORDER BY D.DEPARTMENT_NAME ASC, ISCI_SAYI DESC;


-- TASK 10
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, COUNT(JH.EMPLOYEE_ID) AS KECMIS_VEZIFE_SAYI
FROM HR.EMPLOYEES E
LEFT JOIN HR.JOB_HISTORY JH
ON E.EMPLOYEE_ID = JH.EMPLOYEE_ID 
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME
ORDER BY KECMIS_VEZIFE_SAYI DESC;
