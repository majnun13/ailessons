--TASK 9
SELECT A.FIRST_NAME, A.DEPARTMENT_ID, A.SALARY, B.SOBE_ORTASI AS SOBE_ORTASI, (A.SALARY - B.SOBE_ORTASI) AS FERQ
FROM HR.EMPLOYEES A
JOIN (SELECT DEPARTMENT_ID, AVG(SALARY) AS ESL_ORTA ,ROUND(AVG(SALARY), 0) AS SOBE_ORTASI
      FROM HR.EMPLOYEES 
      GROUP BY DEPARTMENT_ID) B
ON A.DEPARTMENT_ID = B.DEPARTMENT_ID
WHERE A.SALARY > B.ESL_ORTA
ORDER BY FERQ DESC;


