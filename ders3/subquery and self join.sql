SELECT M.FIRST_NAME as MENECER_ADI, M.LAST_NAME AS MENECER_SOYADI, COUNT(*) AS TABE_SAYI
FROM HR.EMPLOYEES A
JOIN HR.EMPLOYEES M
ON A.MANAGER_ID = M.EMPLOYEE_ID
GROUP BY M.FIRST_NAME, M.LAST_NAME
ORDER BY TABE_SAYI DESC;

