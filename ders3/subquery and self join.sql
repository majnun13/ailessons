SELECT DEPARTMENT_NAME, 
       (SELECT COUNT(EMPLOYEE_ID)
        FROM HR.EMPLOYEES E
        WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
WHERE (SELECT COUNT(EMPLOYEE_ID)
        FROM HR.EMPLOYEES E
        WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID) >= 5
ORDER BY ISCI_SAYI DESC;


