SELECT A.FIRST_NAME, A.DEPARTMENT_ID, A.SALARY
FROM HR.EMPLOYEES A
WHERE A.SALARY < (SELECT AVG(B.SALARY)
                  FROM HR.EMPLOYEES B
                  WHERE A.DEPARTMENT_ID = B.DEPARTMENT_ID);

